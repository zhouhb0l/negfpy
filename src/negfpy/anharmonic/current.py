"""Interacting phonon heat-current and collision-power integrals."""

from __future__ import annotations

import numpy as np

from .cubic import cubic_vertex_support
from .grid import SignedFrequencyGrid
from .types import (
    CubicSCBAProblem,
    CurrentReport,
    KeldyshSpectrum,
    SolverScale,
    SpatialCurrentReport,
)


Array = np.ndarray


def _validate_pair(
    self_energy: KeldyshSpectrum,
    green: KeldyshSpectrum,
    grid: SignedFrequencyGrid,
) -> None:
    expected_nw = grid.n_points
    if self_energy.lesser.shape != green.lesser.shape:
        raise ValueError("Self-energy and Green-function spectra must have matching shapes.")
    if self_energy.lesser.shape[0] != expected_nw:
        raise ValueError("Spectrum frequency dimension does not match the signed grid.")


def energy_exchange_spectrum(
    grid: SignedFrequencyGrid,
    self_energy: KeldyshSpectrum,
    green: KeldyshSpectrum,
) -> Array:
    """Return the dimensionless frequency-resolved energy exchange.

    The sign is positive when energy enters the device from the object
    represented by ``self_energy``.
    """

    _validate_pair(self_energy, green, grid)
    exchange = (
        self_energy.greater @ green.lesser
        - self_energy.lesser @ green.greater
    )
    trace = np.trace(exchange, axis1=-2, axis2=-1)
    return np.asarray(grid.values * np.real(trace), dtype=float)


def contact_heat_current(
    grid: SignedFrequencyGrid,
    sigma_contact: KeldyshSpectrum,
    green: KeldyshSpectrum,
    scale: SolverScale,
) -> float:
    """Integrate contact heat current, positive into the device.

    Only strictly positive frequencies are included and the signed grid's
    rectangle weight ``Delta omega / (2 pi)`` is used.
    """

    spectrum = energy_exchange_spectrum(grid, sigma_contact, green)
    dimensionless = float(
        grid.integration_weight * np.sum(spectrum[grid.positive_indices])
    )
    return scale.to_physical_current(dimensionless)


def collision_power(
    grid: SignedFrequencyGrid,
    sigma_pp: KeldyshSpectrum,
    green: KeldyshSpectrum,
    scale: SolverScale,
) -> float:
    """Return integrated energy transfer from the interaction self-energy."""

    return contact_heat_current(grid, sigma_pp, green, scale)


def _validate_problem_pair(
    problem: CubicSCBAProblem,
    self_energy: KeldyshSpectrum,
    green: KeldyshSpectrum,
) -> None:
    if not isinstance(problem, CubicSCBAProblem):
        raise TypeError("problem must be a CubicSCBAProblem.")
    if not isinstance(self_energy, KeldyshSpectrum):
        raise TypeError("self_energy must be a KeldyshSpectrum.")
    if not isinstance(green, KeldyshSpectrum):
        raise TypeError("green must be a KeldyshSpectrum.")
    _validate_pair(self_energy, green, problem.grid)
    expected = (problem.grid.n_points, problem.ndof, problem.ndof)
    if green.shape != expected:
        raise ValueError(f"green must have shape {expected}; got {green.shape}.")


def _project_layer_spectra(
    problem: CubicSCBAProblem,
    matrix_spectrum: Array,
) -> Array:
    """Project one signed matrix kernel onto layers at positive frequency."""

    positive = problem.grid.positive_indices
    frequencies = problem.grid.values[positive]
    spectra = np.zeros(
        (problem.device.n_layers, positive.size),
        dtype=float,
    )
    npl = problem.device.dof_per_layer
    for layer in range(problem.device.n_layers):
        layer_slice = slice(layer * npl, (layer + 1) * npl)
        trace = np.trace(
            matrix_spectrum[:, layer_slice, layer_slice],
            axis1=-2,
            axis2=-1,
        )
        spectra[layer] = (
            problem.scale.current_scale
            * frequencies
            * np.real(trace[positive])
        )
    return spectra


def projected_eom_exchange_spectra(
    problem: CubicSCBAProblem,
    self_energy: KeldyshSpectrum,
    green: KeldyshSpectrum,
) -> Array:
    r"""Return layer-projected Dyson-equation energy-exchange spectra.

    For each layer projector :math:`P_I`, this evaluates

    .. math::

       J_0\,\omega\,\mathrm{Re}\,\mathrm{Tr}\,P_I
       [\Sigma^rG^<+\Sigma^<G^a-G^r\Sigma^<-G^<\Sigma^a]

    at strictly positive frequencies.  Rectangle integration weights are not
    included.  Unlike the greater/lesser collision spectrum, this projected
    equation-of-motion term retains the spatial flow generated by nonlocal
    self-energy blocks.
    """

    _validate_problem_pair(problem, self_energy, green)
    green_advanced = np.swapaxes(green.retarded.conj(), -1, -2)
    sigma_advanced = np.swapaxes(self_energy.retarded.conj(), -1, -2)
    kernel = (
        self_energy.retarded @ green.lesser
        + self_energy.lesser @ green_advanced
        - green.retarded @ self_energy.lesser
        - green.lesser @ sigma_advanced
    )
    return _project_layer_spectra(problem, kernel)


def projected_collision_power_spectra(
    problem: CubicSCBAProblem,
    self_energy: KeldyshSpectrum,
    green: KeldyshSpectrum,
) -> Array:
    """Return layer-projected greater/lesser collision-power spectra.

    The sum over layers is the existing global collision spectrum.  A layer
    projection need not equal :func:`projected_eom_exchange_spectra` when the
    self-energy is nonlocal because cyclic trace rearrangement is then invalid
    inside an individual projector.
    """

    _validate_problem_pair(problem, self_energy, green)
    kernel = (
        self_energy.greater @ green.lesser
        - self_energy.lesser @ green.greater
    )
    return _project_layer_spectra(problem, kernel)


def _harmonic_bond_current_is_valid(problem: CubicSCBAProblem) -> bool:
    """Return whether no retained cubic vertex crosses a layer boundary."""

    explicit = problem.vertex.metadata.get(
        "harmonic_bond_current_supported",
        None,
    )
    npl = problem.device.dof_per_layer
    support = cubic_vertex_support(problem.vertex)
    for first, second, third in support:
        layers = {int(first) // npl, int(second) // npl, int(third) // npl}
        if len(layers) != 1:
            return False
    # Metadata may conservatively disable the operator for a topology with
    # additional interaction-current terms, but it may never override support
    # that demonstrably crosses a device-layer cut.
    return explicit is not False


def bond_heat_current_spectra(
    problem: CubicSCBAProblem,
    green: KeldyshSpectrum,
) -> Array:
    """Return the harmonic current contribution across each device cut.

    The result has shape ``(n_layers - 1, n_positive)`` and is expressed in
    physical current units per dimensionless angular-frequency unit.  Even an
    intralayer cubic vertex generates a nonlocal SCBA self-energy, so this
    harmonic contribution alone is not a conserved spatial current.  The
    projected equation-of-motion correction is recorded separately.  A bare
    bond-cubic vertex crossing a cut requires an additional Hamiltonian
    interaction-current operator and remains rejected.
    """

    if not isinstance(problem, CubicSCBAProblem):
        raise TypeError("problem must be a CubicSCBAProblem.")
    if not isinstance(green, KeldyshSpectrum):
        raise TypeError("green must be a KeldyshSpectrum.")
    expected = (problem.grid.n_points, problem.ndof, problem.ndof)
    if green.shape != expected:
        raise ValueError(f"green must have shape {expected}; got {green.shape}.")
    if not _harmonic_bond_current_is_valid(problem):
        raise NotImplementedError(
            "The harmonic bond-current operator is incomplete because the "
            "cubic vertex crosses a layer boundary."
        )

    n_layers = problem.device.n_layers
    npl = problem.device.dof_per_layer
    positive = problem.grid.positive_indices
    spectra = np.zeros((max(0, n_layers - 1), positive.size), dtype=float)
    for layer, coupling_raw in enumerate(problem.device.coupling_blocks):
        coupling = np.asarray(coupling_raw, dtype=np.complex128)
        left = slice(layer * npl, (layer + 1) * npl)
        right = slice((layer + 1) * npl, (layer + 2) * npl)
        reverse = coupling.conj().T
        for column, iw in enumerate(positive):
            lesser = green.lesser[iw]
            bracket = np.trace(
                coupling @ lesser[right, left]
                - lesser[left, right] @ reverse
            )
            spectra[layer, column] = (
                -problem.scale.current_scale
                * problem.grid.values[iw]
                * float(np.real(bracket))
            )
    return spectra


def bond_heat_currents(
    problem: CubicSCBAProblem,
    green: KeldyshSpectrum,
) -> Array:
    """Integrate the valid harmonic bond-current spectra over frequency."""

    spectra = bond_heat_current_spectra(problem, green)
    return problem.grid.integration_weight * np.sum(spectra, axis=1)


def self_energy_nonlocal_ratio(
    problem: CubicSCBAProblem,
    self_energy: KeldyshSpectrum,
) -> float:
    """Return the aggregate off-layer Frobenius fraction of a self-energy."""

    if not isinstance(problem, CubicSCBAProblem):
        raise TypeError("problem must be a CubicSCBAProblem.")
    if not isinstance(self_energy, KeldyshSpectrum):
        raise TypeError("self_energy must be a KeldyshSpectrum.")
    expected = (problem.grid.n_points, problem.ndof, problem.ndof)
    if self_energy.shape != expected:
        raise ValueError(
            f"self_energy must have shape {expected}; got {self_energy.shape}."
        )
    npl = problem.device.dof_per_layer
    layers = np.arange(problem.ndof) // npl
    off_layer = layers[:, None] != layers[None, :]
    total_squared = 0.0
    off_layer_squared = 0.0
    for component in (
        self_energy.retarded,
        self_energy.lesser,
        self_energy.greater,
    ):
        total_squared += float(np.sum(np.abs(component) ** 2))
        off_layer_squared += float(
            np.sum(np.abs(component[:, off_layer]) ** 2)
        )
    if total_squared == 0.0:
        return 0.0
    return float(np.sqrt(off_layer_squared / total_squared))


def _spatial_current_report(
    problem: CubicSCBAProblem,
    sigma_pp: KeldyshSpectrum,
    green: KeldyshSpectrum,
    *,
    current_left: float,
    current_right: float,
    bond_currents: Array,
) -> SpatialCurrentReport:
    """Build EOM cut closure for an intralayer bare interaction topology.

    The cut correction accounts for nonlocal self-energy blocks. It is not a
    bare interaction-current operator and cannot validate a cross-cut vertex.
    """

    eom_spectra = projected_eom_exchange_spectra(problem, sigma_pp, green)
    collision_spectra = projected_collision_power_spectra(
        problem,
        sigma_pp,
        green,
    )
    weight = problem.grid.integration_weight
    eom_layers = weight * np.sum(eom_spectra, axis=1)
    collision_layers = weight * np.sum(collision_spectra, axis=1)
    bonds = np.asarray(bond_currents, dtype=float).reshape(-1)
    expected_bonds = max(0, problem.device.n_layers - 1)
    if bonds.shape != (expected_bonds,):
        raise ValueError(
            "bond_currents must have shape "
            f"({expected_bonds},); got {bonds.shape}."
        )
    correction = -np.cumsum(eom_layers)[:-1]
    corrected = bonds + correction
    oriented_boundaries = np.concatenate(
        (
            np.asarray([current_left], dtype=float),
            bonds,
            np.asarray([-current_right], dtype=float),
        )
    )
    continuity = np.diff(oriented_boundaries) - eom_layers
    return SpatialCurrentReport(
        sigma_pp_nonlocal_ratio=self_energy_nonlocal_ratio(problem, sigma_pp),
        eom_exchange_spectra=eom_spectra,
        collision_power_spectra=collision_spectra,
        eom_layer_exchange=eom_layers,
        layer_collision_power=collision_layers,
        nonlocal_self_energy_eom_cut_correction=correction,
        corrected_cut_currents=corrected,
        continuity_residual=continuity,
    )


def _evaluate_current_report(
    problem: CubicSCBAProblem,
    sigma_left: KeldyshSpectrum,
    sigma_right: KeldyshSpectrum,
    sigma_pp: KeldyshSpectrum,
    green: KeldyshSpectrum,
) -> CurrentReport:
    """Recompute the complete current report from stored field spectra."""

    current_left = contact_heat_current(
        problem.grid,
        sigma_left,
        green,
        problem.scale,
    )
    current_right = contact_heat_current(
        problem.grid,
        sigma_right,
        green,
        problem.scale,
    )
    power_pp = collision_power(
        problem.grid,
        sigma_pp,
        green,
        problem.scale,
    )
    positive = problem.grid.positive_indices
    spectrum_scale = problem.scale.current_scale
    contact_spectra = np.stack(
        (
            spectrum_scale
            * energy_exchange_spectrum(problem.grid, sigma_left, green)[positive],
            spectrum_scale
            * energy_exchange_spectrum(problem.grid, sigma_right, green)[positive],
        ),
        axis=0,
    )
    collision_spectrum = (
        spectrum_scale
        * energy_exchange_spectrum(problem.grid, sigma_pp, green)[positive]
    )
    spatial = None
    try:
        bond_spectra = bond_heat_current_spectra(problem, green)
        bond_currents = (
            problem.grid.integration_weight * np.sum(bond_spectra, axis=1)
        )
        spatial = _spatial_current_report(
            problem,
            sigma_pp,
            green,
            current_left=current_left,
            current_right=current_right,
            bond_currents=bond_currents,
        )
    except NotImplementedError:
        bond_spectra = None
        bond_currents = None
    return CurrentReport(
        left=current_left,
        right=current_right,
        collision_power=power_pp,
        contact_spectra=contact_spectra,
        collision_spectrum=collision_spectrum,
        bond_currents=bond_currents,
        bond_spectra=bond_spectra,
        spatial=spatial,
    )


